const { _electron: electron, expect } = require('@playwright/test');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
(async()=>{
 const dataDir=fs.mkdtempSync(path.join(os.tmpdir(),'sizzla-desktop-'));
 let app;
 try {
  app=await electron.launch({args:[path.join(__dirname,'..')],env:{...process.env,SIZZLA_DATA_DIR:dataDir}});
  const window=await app.firstWindow();
  await expect(window.getByRole('heading',{name:'Ordning på affärerna.'})).toBeVisible();
  await window.locator('nav').getByRole('button',{name:'Personal'}).click();
  await expect(window.getByRole('button',{name:'Ny anställd'})).toBeVisible();
  await window.locator('nav').getByRole('button',{name:'Bokföring',exact:true}).click();
  await expect(window.getByRole('tab',{name:'Verifikationer'})).toBeVisible();
  await window.locator('nav').getByRole('button',{name:'Inköp',exact:true}).click();
  await expect(window.getByRole('button',{name:'Ny leverantör'})).toBeVisible();
  await app.evaluate(({shell})=>{shell.openPath=async directory=>{global.openedFolder=directory;return '';};});
  await window.locator('nav').getByRole('button',{name:'Säkerhet & säkerhetskopiering',exact:true}).click();
  await window.getByRole('button',{name:'Öppna databasens katalog'}).click();
  await expect.poll(()=>app.evaluate(()=>global.openedFolder)).toBe(dataDir);
  const exportPath=path.join(dataDir,'native-export.sqlite');
  await app.evaluate(({session},destination)=>{session.defaultSession.on('will-download',(event,item)=>{item.setSavePath(destination);item.once('done',(event,status)=>{global.downloadStatus=status;});});},exportPath);
  await window.locator('#backup-form').getByLabel('Kryptera med lösenord').uncheck();
  await window.getByRole('button',{name:'Exportera hela databasen'}).click();
  await expect.poll(()=>app.evaluate(()=>global.downloadStatus)).toBe('completed');
  if(fs.readFileSync(exportPath).subarray(0,16).toString()!=='SQLite format 3\0')throw new Error('Invalid native database export');
  const lock=window.locator('#lock-form');
  await lock.getByLabel('Aktivera programlås').check();
  await lock.getByLabel('Nytt lösenord').fill('1234');
  await lock.getByLabel('Upprepa lösenord').fill('1234');
  await lock.getByRole('button',{name:'Spara',exact:true}).click();
  await expect(window.getByRole('button',{name:/Lås programmet/})).toBeVisible();
  await app.evaluate(({powerMonitor})=>powerMonitor.emit('lock-screen'));
  await expect(window.getByRole('heading',{name:'Sizzla 3000 är låst'})).toBeVisible();
  await window.getByLabel('Lösenord',{exact:true}).fill('1234');
  await window.getByRole('button',{name:'Lås upp',exact:true}).click();
  await expect(window.getByRole('heading',{name:'Ordning på affärerna.'})).toBeVisible();
  await window.locator('nav').getByRole('button',{name:'Lager',exact:true}).click();
  await expect(window.getByRole('heading',{name:'beta kommer senare'})).toBeVisible();
  const preferences=await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].webContents.getLastWebPreferences());
  if(preferences.nodeIntegration || !preferences.contextIsolation || !preferences.sandbox) throw new Error('Unsafe renderer preferences');
  console.log('Desktop startup, local API, beta navigation and renderer isolation passed.');
 } finally {if(app)await app.close();fs.rmSync(dataDir,{recursive:true,force:true});}
})().catch(error=>{console.error(error);process.exitCode=1;});
