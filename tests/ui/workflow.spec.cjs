const { test, expect } = require('@playwright/test');
test('company → customer → article → invoice draft, language and beta tabs',async({page},testInfo)=>{
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('/');
 await page.locator('nav').getByRole('button',{name:'Mitt företag',exact:true}).click();
 await page.getByLabel('Namn').fill('Sizzla Test AB');
 await page.getByLabel('Organisationsnummer').fill('559123-4567');
 await page.getByRole('button',{name:'Spara',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Sparat');
 await page.locator('nav').getByRole('button',{name:'Kunder',exact:true}).click();
 await page.getByRole('button',{name:'Ny kund'}).click();
 await page.getByRole('dialog').getByLabel('Namn').fill('Kund & Partner <AB>');
 await page.getByLabel('E-post').fill('kund@example.se');
 await page.getByRole('button',{name:'Spara',exact:true}).click();
 await expect(page.getByRole('cell',{name:'Kund & Partner <AB>',exact:true})).toBeVisible();
 await page.locator('nav').getByRole('button',{name:'Artiklar & tjänster'}).click();
 await page.getByRole('button',{name:'Ny artikel'}).click();
 await page.getByRole('dialog').getByLabel('Namn').fill('Konsulttimme');
 await page.getByLabel('Pris exkl. moms').fill('800');
 await page.getByRole('button',{name:'Spara',exact:true}).click();
 await expect(page.getByRole('cell',{name:'Konsulttimme',exact:true})).toBeVisible();
 await page.locator('nav').getByRole('button',{name:'Fakturering'}).click();
 await page.getByRole('button',{name:'Nytt fakturautkast'}).click();
 await page.getByLabel('Lägg till från artikelregistret').selectOption({label:'Konsulttimme'});
 await page.getByLabel('Antal', {exact:true}).fill('2.5');
 await expect(page.locator('#totals .grand')).toContainText('2 500,00'.replace(' ','\u00a0'));
 await page.getByRole('button',{name:'Spara',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await expect(page.locator('tbody')).toContainText('Kund & Partner <AB>');
 await page.reload();
 await page.locator('nav').getByRole('button',{name:'Fakturering'}).click();
 await expect(page.locator('tbody tr')).toHaveCount(1);
 await page.getByRole('button',{name:'Öppna'}).click();
 await expect(page.getByLabel('Antal',{exact:true})).toHaveValue('2.50');
 const popupPromise=page.waitForEvent('popup');await page.getByRole('button',{name:'Skriv ut utkast'}).click();
 const popup=await popupPromise;await expect(popup.getByText('UTKAST – EJ FAKTURA')).toBeVisible();
 await expect(popup.locator('.print-sheet')).toContainText('Kund & Partner <AB>');await popup.close();
 await page.getByRole('button',{name:'Avbryt'}).click();
 await page.getByLabel('Sök…').fill('finnsinte');await expect(page.getByText('Inga träffar')).toBeVisible();
 await page.getByLabel('Språk',{exact:true}).selectOption('en');
 await page.locator('nav').getByRole('button',{name:'Accounting',exact:true}).click();
 await expect(page.getByRole('heading',{name:'beta comes later'})).toBeVisible();
 await page.reload();
 await expect(page.locator('html')).toHaveAttribute('lang','en');
 await page.locator('nav').getByRole('button',{name:'Accounting',exact:true}).click();
 await page.getByLabel('Language',{exact:true}).selectOption('sv');
 await expect(page.getByRole('heading',{name:'beta kommer senare'})).toBeVisible();
 await page.locator('nav').getByRole('button',{name:'Översikt',exact:true}).click();
 await page.screenshot({path:testInfo.outputPath('overview.png'),fullPage:true});
 expect(errors).toEqual([]);
});
